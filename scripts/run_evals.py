"""Runs every agent's eval suite and writes EVALS.md.

    python -m scripts.run_evals            # offline planner (or Claude if ANTHROPIC_API_KEY is set)
    python -m scripts.run_evals --min 0.9  # fail if any suite passes fewer than 90% of cases
"""

from __future__ import annotations

import argparse
import os
import sys

from agentkit import load_cases, run_suite
from agents import data_analyst, incident_responder, research_assistant, support_triage

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def cases(agent: str) -> str:
    return os.path.join(ROOT, "agents", agent, "evals", "cases.json")


SUITES = [
    ("Research Assistant (RAG)", research_assistant.make_agent, cases("research_assistant")),
    ("Support Triage (tool calling + approvals)", support_triage.make_agent, cases("support_triage")),
    ("Data Analyst (MCP)", data_analyst.make_agent, cases("data_analyst")),
    ("Incident Responder (MCP + RAG + memory)", incident_responder.make_agent, cases("incident_responder")),
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--min", type=float, default=1.0, help="minimum pass rate per suite (default 1.0)")
    parser.add_argument("--out", default=os.path.join(ROOT, "EVALS.md"))
    args = parser.parse_args()

    sections, ok = [], True
    for name, make_agent, path in SUITES:
        report = run_suite(name, make_agent, load_cases(path),
                           on_case=lambda r: print(f"  {'pass' if r.passed else 'FAIL'}  {r.id}" + (f"  ({'; '.join(r.failures)})" if r.failures else "")))
        print(f"{name}: {report.passed}/{len(report.results)}\n")
        sections.append(report.to_markdown())
        ok &= report.rate >= args.min
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("# Eval results\n\nGenerated by `python -m scripts.run_evals`. Each case runs on a fresh agent; checks cover the "
                     "final answer and the trajectory (tools called, approvals, steps).\n\n" + "\n".join(sections))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
